(* [snapshot] prints an OCaml module that holds the standard library's trees,
   as Driver.std_snapshot gives them, so that stilt-ref is built with them
   and doesn't parse the library at each command. *)

let () =
  print_endline "(* Generated by interpreter/gen/snapshot.ml. *)";
  Printf.printf "let data = %S\n" (Stilt.Driver.std_snapshot ())
