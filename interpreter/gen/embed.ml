(* [embed ROOT FILE...] prints an OCaml module that holds the files, each
   named by its path below the directory ROOT, so that the standard library is
   built into stilt-ref. *)

let () =
  match Array.to_list Sys.argv with
  | _ :: root :: files ->
      let prefix = root ^ "/" in
      print_endline "(* Generated by interpreter/gen/embed.ml. *)";
      print_endline "let files = [";
      List.iter
        (fun path ->
          if not (String.starts_with ~prefix path) then
            failwith (path ^ " is not below " ^ root);
          let name =
            String.sub path (String.length prefix)
              (String.length path - String.length prefix)
          in
          let text = In_channel.with_open_bin path In_channel.input_all in
          Printf.printf "  (%S, %S);\n" name text)
        files;
      print_endline "]"
  | _ -> failwith "usage: embed ROOT FILE..."
