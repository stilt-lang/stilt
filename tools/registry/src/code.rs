//! The registry as code: the compiler's constants, the reference interpreter's values, the
//! language server's table of the codes the error index describes, and the list of codes that
//! the coverage report expects tests of.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::paragraphs::Paragraph;
use crate::registry::{Entry, Example};
use crate::{COMMAND, Generated};

/// Where the error index's pages are published: the page of the code `C` is `INDEX` followed
/// by `C.md`.
pub(crate) const INDEX: &str = "https://github.com/stilt-lang/stilt/blob/main/docs/errors/";

/// The header of a Rust file generated from `sources`, wrapped at 100 columns.
fn header(sources: &str) -> String {
    let text =
        format!("Generated by `{COMMAND}` from {sources}: edit the registry, not this file.");
    let mut out = String::from("//");
    let mut column = 2;
    for word in text.split(' ') {
        if column + 1 + word.len() > 100 {
            out.push_str("\n//");
            column = 2;
        }
        out.push(' ');
        out.push_str(word);
        column += 1 + word.len();
    }
    out.push('\n');
    out
}

/// The compiler's constants, one per code, in `compiler/stilt-diag/src/codes.rs`.
pub(crate) fn rust(entries: &[Entry], paragraphs: &BTreeMap<String, Paragraph>) -> Generated {
    let mut out = header("reference/errors.toml and the Reference's paragraphs it names");
    out.push_str(
        "\n//! The registered codes, one constant each, so that only a registered code can be \
         reported\n//! (goal registered-codes).\n\n",
    );
    let any_example = entries.iter().any(|e| !e.examples.is_empty());
    let used = if any_example {
        "Code, Entry, Example"
    } else {
        "Code, Entry"
    };
    let _ = writeln!(out, "use crate::registry::{{{used}}};\n");
    for e in entries {
        let rule = paragraphs.get(&e.reference).map_or("", |p| p.text.as_str());
        let examples: Vec<String> = e.examples.iter().map(rust_example).collect();
        let _ = writeln!(out, "/// {}", e.title);
        let _ = writeln!(
            out,
            "pub const {code}: Code = Code(&Entry {{ code: {code:?}, title: {:?}, reference: {:?}, \
             rule: {rule:?}, tier: {:?}, phase: {:?}, help: {:?}, span: {:?}, retired: {}, \
             examples: &[{}] }});",
            e.title,
            e.reference,
            e.tier,
            e.phase,
            e.help,
            e.span,
            e.retired,
            examples.join(", "),
            code = e.code,
        );
    }
    let all: Vec<&str> = entries.iter().map(|e| e.code.as_str()).collect();
    let _ = writeln!(out, "\n/// Every code of the registry, in its order.");
    let _ = writeln!(out, "pub const ALL: &[Code] = &[{}];", all.join(", "));
    Generated::new("compiler/stilt-diag/src/codes.rs", out)
}

fn rust_example(x: &Example) -> String {
    format!(
        "Example {{ wrong: {:?}, line: {}, right: {:?} }}",
        x.wrong, x.line, x.right
    )
}

/// The reference interpreter's values, one per code, in `interpreter/lib/code.ml` and its
/// interface.
pub(crate) fn ocaml(entries: &[Entry]) -> [Generated; 2] {
    let head = format!(
        "(* Generated by `{COMMAND}` from reference/errors.toml: edit\n   \
         the registry, not this file. *)\n"
    );
    let mut ml = format!("{head}\ntype t = string\n\n");
    let mut mli = format!(
        "{head}\n(** The codes of the registry, one value each, named as the code is in\n    \
         lowercase, so that only a registered code can be reported (goal\n    \
         registered-codes). *)\n\ntype t = private string\n\n"
    );
    for e in entries {
        let name = e.code.to_lowercase();
        let _ = writeln!(ml, "let {name} = {:?}", e.code);
        let _ = writeln!(mli, "val {name} : t");
    }
    [
        Generated::new("interpreter/lib/code.ml", ml),
        Generated::new("interpreter/lib/code.mli", mli),
    ]
}

/// The codes whose pages the language server links each diagnostic to, in
/// `compiler/stilt-lsp/src/codes.rs`.
pub(crate) fn lsp(entries: &[Entry]) -> Generated {
    let mut out = header("reference/errors.toml");
    out.push_str(
        "\n//! The codes that the error index has a page for, which an editor links each \
         diagnostic's\n//! code to (the protocol's `codeDescription`).\n\n",
    );
    let _ = writeln!(
        out,
        "/// Where the pages are: the page of the code `C` is `INDEX` followed by `C.md`."
    );
    let _ = writeln!(out, "pub(crate) const INDEX: &str = {INDEX:?};\n");
    let mut codes: Vec<String> = entries.iter().map(|e| format!("{:?}", e.code)).collect();
    codes.sort();
    let _ = writeln!(
        out,
        "/// The codes, sorted, so that a lookup can search them."
    );
    let _ = writeln!(
        out,
        "pub(crate) const CODES: &[&str] = &[{}];",
        codes.join(", ")
    );
    Generated::new("compiler/stilt-lsp/src/codes.rs", out)
}

/// The codes that implementations may report, with the home, the tier and the phase of each,
/// in `tools/runner/src/coverage/codes.rs`.
pub(crate) fn coverage(entries: &[Entry]) -> Generated {
    let mut out = header("reference/errors.toml");
    out.push_str(
        "\n//! The codes of the registry that implementations may report, every one but the \
         retired\n//! ones, whose tests the coverage report expects.\n\n\
         use super::registry::Registered;\nuse crate::annotations::Tier;\n\n\
         /// The codes, in the registry's order.\npub(super) const CODES: &[Registered] = &[\n",
    );
    for e in entries.iter().filter(|e| !e.retired) {
        let mut tier = e.tier.clone();
        tier[..1].make_ascii_uppercase();
        let _ = writeln!(
            out,
            "    Registered {{ code: {:?}, reference: {:?}, tier: Tier::{tier}, phase: {:?} }},",
            e.code, e.reference, e.phase
        );
    }
    out.push_str("];\n");
    Generated::new("tools/runner/src/coverage/codes.rs", out)
}
