//! The error index, `docs/errors/`: a page per code, with its help, its rule, examples of the
//! mistake and of its fix, which `just guide` checks as it checks the guide's, and what the
//! compiler prints for each of the code's snapshots; and a page that lists the codes.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::paragraphs::Paragraph;
use crate::registry::Entry;
use crate::snapshots::{self, Snapshot};
use crate::{COMMAND, Generated};

/// Where the error index is, from the repository's root.
pub(crate) const DIR: &str = "docs/errors";

/// The sections of the list of codes, each with the first three characters of its codes, as
/// the registry's ranges give them.
const SECTIONS: [(&str, &[&str]); 8] = [
    ("Lexical structure", &["E00", "W00"]),
    ("Syntax", &["E01"]),
    ("Modules and names", &["E02"]),
    ("Types and traits", &["E03", "W03"]),
    ("Modes and exclusivity", &["E04"]),
    ("Effects and failure", &["E05", "W05"]),
    ("Packages and the profiles beside their manifests", &["E06"]),
    ("Edits that a command refuses", &["E07"]),
];

/// The header of each page.
fn header() -> String {
    format!(
        "<!-- Generated by `{COMMAND}` from reference/errors.toml and the snapshots of {}: \
         edit those, not this file. -->\n\n",
        snapshots::DIR
    )
}

/// The pages of the index: one per code, and the list of codes.
pub(crate) fn pages(
    entries: &[Entry],
    paragraphs: &BTreeMap<String, Paragraph>,
    snapshots: &BTreeMap<String, Vec<Snapshot>>,
) -> Vec<Generated> {
    let none = Vec::new();
    let mut pages: Vec<Generated> = entries
        .iter()
        .map(|e| {
            let found = snapshots.get(&e.code).unwrap_or(&none);
            let text = page(e, &paragraphs[&e.reference], found);
            Generated::new(format!("{DIR}/{}.md", e.code), text)
        })
        .collect();
    pages.push(Generated::new(format!("{DIR}/README.md"), list(entries)));
    pages
}

/// The page of `e`, whose home is `home` and whose snapshots are `snapshots`.
fn page(e: &Entry, home: &Paragraph, snapshots: &[Snapshot]) -> String {
    let mut out = header();
    let _ = writeln!(out, "# {}: {}\n", e.code, e.title);
    if e.retired {
        out.push_str("This code is retired: no implementation reports it.\n\n");
    }
    let _ = writeln!(out, "{}\n", e.help);
    let _ = writeln!(
        out,
        "- Rule: [`{id}`](../../reference/{}#{id})",
        home.chapter,
        id = e.reference
    );
    let _ = writeln!(out, "- Reported at: {}", lowercase_first(&e.span));
    let _ = writeln!(
        out,
        "- Tier: `{}`, checked in the `{}` phase",
        e.tier, e.phase
    );
    for (i, x) in e.examples.iter().enumerate() {
        let title = if e.examples.len() == 1 {
            "## Example".to_owned()
        } else {
            format!("## Example {}", i + 1)
        };
        let _ = writeln!(
            out,
            "\n{title}\n\nThis program makes the mistake:\n\n```stilt {}:{}\n{}```\n\n\
             This one is fixed:\n\n```stilt\n{}```",
            e.code, x.line, x.wrong, x.right
        );
    }
    if !snapshots.is_empty() {
        out.push_str("\n## What the compiler prints\n");
    }
    for s in snapshots {
        out.push_str(&rendering(s));
    }
    out
}

/// What the compiler prints for the program of `s`, after the program when it isn't one file.
fn rendering(s: &Snapshot) -> String {
    let link = format!("[`{}`](../../{}/{})", s.name, snapshots::DIR, s.name);
    let mut out = String::new();
    if s.is_one_file() {
        let _ = writeln!(out, "\n`stilt check` on {link}:");
    } else {
        let _ = writeln!(out, "\nThe program {link}:");
        for (path, text) in &s.files {
            let lang = if snapshots::is_source(path) {
                "stilt fragment"
            } else {
                "text"
            };
            let _ = writeln!(out, "\n`{path}`:\n\n```{lang}\n{text}```");
        }
        for (name, text) in &s.fixtures {
            let _ = writeln!(out, "\n`{name}`, beside it:\n\n```text\n{text}```");
        }
        if s.repos {
            let _ = writeln!(
                out,
                "\nThe repositories it fetches from are beside it, in `{}`.",
                s.name.replace(".lt", "") + ".repos"
            );
        }
        out.push_str("\nWhat `stilt check` prints for it:\n");
    }
    let _ = writeln!(out, "\n```text\n{}```", s.rendering);
    out
}

/// The page that lists the codes, by range.
fn list(entries: &[Entry]) -> String {
    let mut out = header();
    out.push_str(
        "# The error index\n\nEvery code that Stilt's diagnostics carry, each with a page that \
         says what it means and what to do about it, shows a program that makes the mistake and \
         the same program fixed, and gives what the compiler prints. `stilt show CODE` prints \
         the same help and examples in the terminal. Each example is checked as the guide's are, \
         by `just guide`, and each rendering by `just diagnostics`.\n",
    );
    for (title, prefixes) in SECTIONS {
        let _ = writeln!(out, "\n## {title}\n\n| Code | Title |\n| --- | --- |");
        for e in entries
            .iter()
            .filter(|e| prefixes.iter().any(|p| e.code.starts_with(p)))
        {
            let _ = writeln!(out, "| [{code}]({code}.md) | {} |", e.title, code = e.code);
        }
    }
    out
}

/// `text` with its first letter in lowercase, unless the word it starts is a name in capitals.
fn lowercase_first(text: &str) -> String {
    let mut chars = text.chars();
    match (chars.next(), chars.next()) {
        (Some(first), Some(second)) if first.is_uppercase() && second.is_lowercase() => {
            first.to_lowercase().chain(text.chars().skip(1)).collect()
        }
        _ => text.to_owned(),
    }
}
